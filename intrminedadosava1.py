def geradorHipoteses(nvariaveis, max_value ):
  #Objetivo: agrupar o valor das variáveis apresentadas e informar todas as
  # conjuções com até 3 variáveis (incluindo sua negação).
  variaveis = list()
  for p in range (1, nvariaveis+1):
    # Laço que gera as variaveis acompanhadas de seu numerador correspondente
    x = "x" + str(p)
    negx = "¬" + x
    variaveis.append(x)
    variaveis.append(negx)
    hipoteses = list()
  # Laço para definir o valor de combinações das variaveis

  for tamanho in range(1, max_value + 1):
        hipoteses.extend(combinations(variaveis, tamanho))


  return hipoteses

