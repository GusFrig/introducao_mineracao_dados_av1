def removerhipotesesincoerentes(hipoteses):
    # Objetivo: Remover hipóteses incoerentes (ex: 'x1' e '¬x1') e duplicadas
    hipoteses_validas = []

    for hipotese in hipoteses:
        # Extrai os nomes base das variáveis (ex: '¬x1' vira 'x1')
        variaveis_base = [termo.replace('¬', '') for termo in hipotese]

        # Se a quantidade de variáveis únicas for igual ao número de termos,
        # não há contradições (ex: x1 e ¬x1) nem elementos repetidos.
        if len(set(variaveis_base)) == len(hipotese):
            hipoteses_validas.append(hipotese)

    return hipoteses_validas

def avalia_hipotese(hipotese, exemplo):
    # objetivo: analisar os termo da hipotese
    for termo in hipotese:
        if termo.startswith("¬"):
            indice = int(termo[2:]) - 1  # Converte ¬x1 -> índice 0
            if exemplo[indice] != 0:
                return False
        else:
            indice = int(termo[1:]) - 1   # Converte x1 -> índice 0
            if exemplo[indice] != 1:
                return False
    return True

def comparadorHipoteses_Estatistico(conjuntotreinamento, hipoteses):
    resultados = []
    exemplos_classe0 = conjuntotreinamento[0]
    exemplos_classe1 = conjuntotreinamento[1]
    total_exemplos = len(exemplos_classe0) + len(exemplos_classe1)

    for hipotese in hipoteses:
        tp = sum(1 for ex in exemplos_classe1 if avalia_hipotese(hipotese, ex))
        fp = sum(1 for ex in exemplos_classe0 if avalia_hipotese(hipotese, ex))
        tn = len(exemplos_classe0) - fp

        acuracia = (tp + tn) / total_exemplos

        resultados.append({
            'Hipotese': hipotese,
            'Acertos_Cls1': tp,
            'Erros_Cls0': fp,
            'Acuracia': round(acuracia, 4)
        })

    return sorted(resultados, key=lambda x: x['Acuracia'], reverse=True)

